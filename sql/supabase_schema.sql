-- Ejecutar solo después de revisar el esquema del bot existente.
-- Usa nombres aislados para no modificar tablas actuales.
create table if not exists public.fuelintel_items (
  content_hash text primary key,
  canonical_url text not null,
  source_id text not null,
  source_name text not null,
  title text not null,
  published_at timestamptz,
  detected_at timestamptz not null,
  status text not null check (status in ('verified', 'pending', 'rejected', 'stale', 'duplicate')),
  confidence smallint not null check (confidence between 0 and 100),
  reasons jsonb not null default '[]'::jsonb,
  notified_at timestamptz
);

create table if not exists public.fuelintel_prices (
  id bigint generated by default as identity primary key,
  product text not null,
  price numeric(12,4) not null check (price > 0),
  currency text not null default 'USD',
  unit text not null default 'galón',
  effective_from date,
  effective_to date,
  source_url text not null,
  observed_at timestamptz not null,
  unique (product, price, effective_from, effective_to, source_url)
);

create index if not exists fuelintel_items_detected_idx on public.fuelintel_items (detected_at desc);
create index if not exists fuelintel_prices_product_period_idx on public.fuelintel_prices (product, effective_from desc);

alter table public.fuelintel_items enable row level security;
alter table public.fuelintel_prices enable row level security;

